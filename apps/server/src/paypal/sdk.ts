import { Client, Environment, OrdersController, PaymentsController, type Order, type OrderRequest } from '@paypal/paypal-server-sdk';
import type { PayPalOrderView } from '@faircart/guard';
import { PayPalRest } from './client';
import type { Capture, OrderBody, PayPal } from './types';

/** Our Orders v2 body → the SDK's request model (APIMatic models use camelCase). */
export function toSdkOrder(body: OrderBody): OrderRequest {
  return {
    intent: body.intent as OrderRequest['intent'],
    ...(body.payment_source ? { paymentSource: { paypal: { vaultId: body.payment_source.paypal.vault_id } } } : {}),
    purchaseUnits: body.purchase_units.map((pu) => ({
      invoiceId: pu.invoice_id,
      customId: pu.custom_id,
      description: pu.description,
      amount: { currencyCode: pu.amount.currency_code, value: pu.amount.value, breakdown: { itemTotal: { currencyCode: pu.amount.breakdown.item_total.currency_code, value: pu.amount.breakdown.item_total.value } } },
      items: pu.items.map((i) => ({ name: i.name, quantity: i.quantity, unitAmount: { currencyCode: i.unit_amount.currency_code, value: i.unit_amount.value }, category: i.category as never })),
    })),
  } as OrderRequest;
}

/** An SDK order → the view FairCart compares with the cart mandate. */
export function fromSdkOrder(o: Pick<Order, 'status' | 'purchaseUnits'>): PayPalOrderView & { status: string } {
  const pu = o.purchaseUnits?.[0];
  return {
    status: String(o.status ?? ''),
    currency: pu?.amount?.currencyCode ?? '',
    total: pu?.amount?.value ?? '',
    items: (pu?.items ?? []).map((i) => ({ name: i.name, quantity: i.quantity, unit_amount: { value: i.unitAmount.value } })),
  };
}

/**
 * PayPal through PayPal's official TypeScript Server SDK (generated by APIMatic)
 * for Orders and Payments. Vault setup tokens and webhook verification use the
 * REST client: the SDK's vault PayPal-wallet model has no experience context
 * (return URL), and it has no webhook verification call.
 */
export class PayPalSdk implements PayPal {
  private readonly orders: OrdersController;
  private readonly payments: PaymentsController;
  private readonly rest: PayPalRest;

  constructor(cfg: { clientId: string; clientSecret: string; webhookId: string }) {
    const client = new Client({
      clientCredentialsAuthCredentials: { oAuthClientId: cfg.clientId, oAuthClientSecret: cfg.clientSecret },
      environment: Environment.Sandbox,
      timeout: 20_000,
    });
    this.orders = new OrdersController(client);
    this.payments = new PaymentsController(client);
    this.rest = new PayPalRest(cfg);
  }

  async createOrder(body: OrderBody, requestId: string) {
    const { result } = await this.orders.createOrder({ body: toSdkOrder(body), paypalRequestId: requestId, prefer: 'return=representation' });
    const authorizationId = result.purchaseUnits?.[0]?.payments?.authorizations?.[0]?.id;
    return { id: result.id!, status: String(result.status), ...(authorizationId ? { authorizationId } : {}) };
  }

  async getOrder(id: string) {
    const { result } = await this.orders.getOrder({ id });
    return fromSdkOrder(result);
  }

  async captureOrder(id: string): Promise<Capture> {
    const { result } = await this.orders.captureOrder({ id, paypalRequestId: `capture-${id}`, prefer: 'return=representation' });
    const c = result.purchaseUnits?.[0]?.payments?.captures?.[0];
    if (!c?.id) throw new Error('PayPal returned no capture');
    return { id: c.id, status: String(c.status), amount: c.amount?.value ?? '' };
  }

  async authorizeOrder(orderId: string, requestId: string) {
    const { result } = await this.orders.authorizeOrder({ id: orderId, paypalRequestId: requestId, prefer: 'return=representation' });
    const a = result.purchaseUnits?.[0]?.payments?.authorizations?.[0];
    if (!a?.id) throw new Error('PayPal returned no authorization');
    return { authorizationId: a.id, status: String(a.status) };
  }

  async captureAuthorization(authorizationId: string, requestId: string): Promise<Capture> {
    const { result } = await this.payments.captureAuthorizedPayment({ authorizationId, paypalRequestId: requestId, prefer: 'return=representation', body: {} });
    return { id: result.id!, status: String(result.status), amount: result.amount?.value ?? '' };
  }

  async voidAuthorization(authorizationId: string) {
    await this.payments.voidPayment({ authorizationId });
  }

  createSetupToken(urls: { returnUrl: string; cancelUrl: string }, requestId: string) {
    return this.rest.createSetupToken(urls, requestId);
  }

  createPaymentToken(setupTokenId: string, requestId: string) {
    return this.rest.createPaymentToken(setupTokenId, requestId);
  }

  verifyWebhook(headers: Record<string, string>, rawBody: string) {
    return this.rest.verifyWebhook(headers, rawBody);
  }
}
